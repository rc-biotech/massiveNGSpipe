test_that('anchored polyC is longest exact4–6 match, preserving IDs, qualities and real sequence', {
  x <- c('CCCCCCATGCTA','CCCCCATGCTA','CCCCATGCTA','CCCATGCTA','ATGCCCCCC','CCCCCCCCATGCTA')
  quality <- vapply(nchar(x), function(n) paste0(rep(c('A','B','C','D'), length.out=n), collapse=''), character(1))
  fq <- ShortRead::ShortReadQ(Biostrings::DNAStringSet(x), Biostrings::BStringSet(quality), Biostrings::BStringSet(paste0('read',seq_along(x))))
  z <- anchored_front_chunk(fq, 'C', 4L, 6L)
  expect_equal(z$cut, c(6L,5L,4L,0L,0L,6L))
  expect_equal(as.character(ShortRead::sread(z$reads)), c('ATGCTA','ATGCTA','ATGCTA','CCCATGCTA','ATGCCCCCC','CCATGCTA'))
  expect_equal(as.character(Biostrings::quality(Biostrings::quality(z$reads))), substring(quality,z$cut+1L))
  expect_identical(ShortRead::id(z$reads),ShortRead::id(fq))
})

