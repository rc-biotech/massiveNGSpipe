test_that('streamed FASTQ processing reconciles final counts and qualities with original reports', {
  fastp<-Sys.which('fastp');if(!nzchar(fastp))fastp<-path.expand('~/bin/fastp')
  skip_if_not(file.exists(fastp))
  root<-tempfile('anchor space ');dir.create(root)
  file<-file.path(root,'trimmed_SRR_anchor.fastq');report<-file.path(root,'report_SRR_anchor.json')
  insert<-'ATGGAATTTCCAGCTGACCTAGACCTTACAG'
  x<-c(paste0('CCCCCC',insert),paste0('CCCC',insert),'CCCCCCACGT',paste0('CCC',insert))
  lines<-unlist(lapply(seq_along(x),function(i)c(paste0('@id',i),x[i],'+',strrep('I',nchar(x[i])))))
  writeLines(lines,file)
  original<-list(summary=list(before_filtering=list(total_reads=5,total_bases=500,read1_mean_length=100),after_filtering=list(total_reads=4),sequencing='single end'), filtering_result=list(passed_filter_reads=4,too_short_reads=1), command='first adapter and UMI steps', read1_before_filtering=list(total_cycles=100))
  jsonlite::write_json(original,report,auto_unbox=TRUE)
  result<-anchored_front_trim_fastq(file,list(base='C',min=4L,max=6L),report,chunk_size=2L,threads=2L,fastp_path=fastp)
  fq<-ShortRead::readFastq(file)
  expect_equal(as.character(ShortRead::sread(fq)),c(insert,insert,paste0('CCC',insert)))
  expect_equal(Biostrings::width(Biostrings::quality(fq)),nchar(c(insert,insert,paste0('CCC',insert))))
  expect_equal(as.character(ShortRead::id(fq)),c('id1','id2','id4'))
  j<-jsonlite::fromJSON(report)
  expect_equal(j$summary$before_filtering$total_reads,5)
  expect_equal(j$summary$after_filtering$total_reads,3)
  expect_equal(j$filtering_result$too_short_reads,2)
  expect_equal(j$summary$after_filtering$total_bases,sum(nchar(c(insert,insert,paste0('CCC',insert)))))
  expect_equal(j$massiveNGSpipe_anchored_front$input_records,4)
  expect_equal(j$massiveNGSpipe_anchored_front$matched_records,3)
  expect_equal(result$removed_bases,16)
  expect_true(file.exists(file.path(root,'trim_order_metrics','SRR_anchor_before_anchored_front.json')))
  expect_false(any(grepl('anchored_input_|anchored_output_|anchored_report_',list.files(root))))
})
