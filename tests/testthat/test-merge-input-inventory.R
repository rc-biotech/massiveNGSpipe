test_that("merge inventory records actual files, mapper and UTC modification time", {
  d <- tempfile(); dir.create(d)
  a <- file.path(d, "study pool.ofst"); b <- file.path(d, "unique.ofst")
  writeBin(as.raw(1:3), a); writeBin(as.raw(1:5), b)
  Sys.setFileTime(a, as.POSIXct("2020-01-02 03:04:05", tz = "UTC"))
  x <- merge_input_file_inventory(c(a, b), c("all", "unique"))
  expect_equal(x$mapper, c("all", "unique"))
  expect_equal(x$path, normalizePath(c(a, b), winslash = "/"))
  expect_equal(x$size_bytes, c(3, 5))
  expect_match(x$modified_utc[1], "^2020-01-02T03:04:05")
  expect_match(x$modified_utc, "Z$")
  writeBin(as.raw(1:6), b)
  expect_false(identical(x, merge_input_file_inventory(c(a, b), c("all", "unique"))))
  expect_error(merge_input_file_inventory(file.path(d, "missing"), "all"))
})
